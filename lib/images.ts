import crypto from 'node:crypto';
import fs from 'node:fs';
import path from 'node:path';

/**
 * Build-time photo discovery. Drop a photo into public/products/ named by the
 * SKU slug (e.g. signature.jpg) — or hero.jpg, lifestyle-1.jpg … — rebuild,
 * and the site automatically upgrades that slot from vector art to the photo.
 * Runs only on the server at prerender time.
 *
 * URLs carry a short content hash (?v=…) so every browser/CDN/Next-optimizer
 * cache busts automatically whenever a file's contents change — replacing an
 * image never requires a cache-clear or a rename again.
 */

const exts = ['jpg', 'jpeg', 'webp', 'png'];

/** ?v= content-hash a public/ relative URL, or null when the file is missing. */
export function hashedPath(rel: string): string | null {
  const abs = path.join(process.cwd(), 'public', rel);
  if (!fs.existsSync(abs)) return null;
  const v = crypto.createHash('md5').update(fs.readFileSync(abs)).digest('hex').slice(0, 8);
  return `${rel}?v=${v}`;
}

export function productImage(slug: string): string | null {
  for (const ext of exts) {
    const url = hashedPath(`/products/${slug}.${ext}`);
    if (url) return url;
  }
  return null;
}

/**
 * Tiny blur placeholders, generated by scripts/generate-media.mjs (prebuild)
 * into lib/lqip.json as {slug: dataURI}. Read defensively so a missing file
 * (fresh clone before the first build) never breaks anything.
 */
const lqip: Record<string, string> = (() => {
  try {
    const p = path.join(process.cwd(), 'lib', 'lqip.json');
    if (fs.existsSync(p)) return JSON.parse(fs.readFileSync(p, 'utf8'));
  } catch {
    /* fall through to empty map */
  }
  return {};
})();

/** Blur data URI for a product slug — also accepts a productImage() URL. */
export function blurFor(slugOrUrl: string): string | undefined {
  const slug = slugOrUrl
    .split('?')[0]
    .replace(/^.*\//, '')
    .replace(/\.(jpg|jpeg|webp|png)$/i, '');
  return lqip[slug];
}

/** Spreadable next/image props: {placeholder, blurDataURL} when a LQIP exists, {} otherwise. */
export function blurProps(slugOrUrl: string | null | undefined) {
  const blur = slugOrUrl ? blurFor(slugOrUrl) : undefined;
  return blur ? ({ placeholder: 'blur', blurDataURL: blur } as const) : {};
}

/** Numbered series, e.g. lifestyle-1.jpg, lifestyle-2.jpg … in order. */
export function imageSeries(prefix: string, max = 8): string[] {
  const found: string[] = [];
  for (let i = 1; i <= max; i++) {
    const img = productImage(`${prefix}-${i}`);
    if (img) found.push(img);
  }
  return found;
}
